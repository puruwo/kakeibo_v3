/// ============================================================================
/// アプリ全般で共通して使用する余白グリッド（ADR-017 #3）を定義
///
/// 余白は 4px 刻みのグリッドに揃える。ここに無い値を新規に使わないこと。
/// ============================================================================
class AppSpacing {
  /// 4px — 最小単位。タイトルと補助テキスト・ラベル同士の微小な区切り
  static const double xs = 4;

  /// 8px — 関連要素の間（アイコンとテキスト・カード内の行間）
  static const double sm = 8;

  /// 12px — カード内のブロック間・コンパクトな内周パディング
  static const double md = 12;

  /// 16px — 標準余白。カード内周・画面端・セクション内の標準間隔
  static const double lg = 16;

  /// 24px — セクション間の大きめの区切り
  static const double xl = 24;

  /// 32px — 画面レベルの大余白
  static const double xxl = 32;
}
